WITNESS = '''# Auto-generated by ESBMC 8.6.0
# Original file: h.py

witness = [
    {"arg0": "llls", "arg1": 3},
    {"arg0": "ab"},
]
'''


def test_the_witness_file_gives_its_values_in_order():
    assert parse_witness(WITNESS) == ["llls", 3, "ab"]


def test_a_file_without_a_witness_gives_nothing():
    assert parse_witness("# Auto-generated by ESBMC\n") == []
    assert parse_witness("witness = [oops") == []


def test_string_seeds_steer_the_replay():
    # No default or constant breaks it; only the value ESBMC found does.
    source = '''def f(s):
    if len(s) == 3 and ord(s[1]) == 57:
        raise ValueError(s)


def main() -> None:
    s: str = nondet_str()
    f(s)


main()
'''
    program = Program(source, 7, ((3, 3),), (), target_range=(1, 3))
    assert concrete_replay(program, "f").status == "not_reproduced"
    verdict = concrete_replay(program, "f", seeds={"int": [], "float": [], "str": ["x9x"]})
    assert (verdict.status, verdict.exception_type, verdict.line) == ("reproduced", "ValueError", 3)


@pytest.mark.skipif(shutil.which("esbmc") is None, reason="needs ESBMC")
def test_esbmc_gives_back_the_string_it_found(tmp_path):
    path = tmp_path / "p.py"
    path.write_text("s: str = nondet_str()\nassert s != 'ab'\n", encoding="utf-8")
    assert "ab" in string_witness(path, esbmc_command=["esbmc"], bound=5, timeout_seconds=120,
                                  work_dir=tmp_path / "w")


SECRET = "def check(s):\n    return not (len(s) == 3 and ord(s[1]) == 57)\n"
SECRET_FIXED = "def check(s):\n    return True\n"


def _esbmc_with_a_hidden_string(path, extra_flags=None, **_):
    """The run fails at the driver's assert; asked for a pytest witness, it writes the string there."""
    path = Path(path)
    lines = path.read_text(encoding="utf-8").splitlines()
    line = next(n for n, text in enumerate(lines, 1) if text.strip().startswith("assert "))
    flags = extra_flags or []
    if "--generate-pytest-testcase" in flags:
        out = Path(flags[flags.index("--pytest-output-dir") + 1])
        out.mkdir(parents=True, exist_ok=True)
        (out / f"test_{path.stem}.py").write_text('witness = [\n    {"arg0": "x9x"},\n]\n', encoding="utf-8")
    return ESBMCDirectResult(source_file=str(path), status="violation_found", command=["esbmc"], returncode=1,
                             summary="violation_found",
                             details={"violated_properties": ["assertion"], "violated_files": [""],
                                      "violated_property_records": [{"kind": "assertion", "line": line}]})


def _verify_secret(tmp_path, monkeypatch, runner):
    monkeypatch.setattr(esbmc_run, "run_esbmc_direct", runner)
    monkeypatch.setattr(string_witness_module, "run_esbmc_direct", runner)
    monkeypatch.setattr(loop, "convert", lambda source, command: "")
    spec = json.dumps({"params": {"s": "str"}, "returns": "bool", "postcondition": "result"})
    llm = type("Fixed", (), {"model": "fixed", "complete": lambda self, *a, **k: SynthResult(
        harness=spec, raw_response="", model="fixed", telemetry={})})()
    h = BugHypothesis("m.py", "check", "ord(s[1]) == 57", oracle=VALUE_ORACLE)
    return loop.verify_hypothesis(h, llm=llm, source=SECRET, esbmc_command=["esbmc"], bound=5, timeout_seconds=30,
                                  work_dir=tmp_path, fixed_source=SECRET_FIXED)


def test_the_string_esbmc_hid_reaches_the_replay(tmp_path, monkeypatch):
    result = _verify_secret(tmp_path, monkeypatch, _esbmc_with_a_hidden_string)
    assert result.verdict == VALUE_CONFIRMED
    assert result.replay["inputs"] == ["x9x"]
    assert result.attempts[-1]["witness_strings"] == ["x9x"]
